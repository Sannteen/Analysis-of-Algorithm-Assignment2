
import java.util.ArrayList;
import java.util.List;

public class Main {

    public static void main(String[] args) {

        // Create a list of jobs to schedule.
        List<Job> jobs = new ArrayList<>();

        jobs.add(new Job("A", 150, 3, 0, 0));
        jobs.add(new Job("B", 80, 1, 0, 0));
        jobs.add(new Job("C", 90, 1, 1, 1));
        jobs.add(new Job("D", 250, 3, 0, 0));
        jobs.add(new Job("E", 60, 1, 2, 2));

        // Display the jobs available for scheduling.
        displayAvailableJobs(jobs);

        // Execute the greedy scheduling algorithm.
        GreedyScheduler.Result greedyResult =
                GreedyScheduler.schedule(jobs);

        // Execute the brute-force scheduling algorithm.
        GreedyScheduler.Result bruteForceResult =
                BruteForceScheduler.schedule(jobs);

        // Display the results of both algorithms.
        displayResult(
                "GREEDY SCHEDULER RESULTS",
                greedyResult
        );

        displayResult(
                "BRUTE FORCE SCHEDULER RESULTS",
                bruteForceResult
        );

        // Compare the total profit generated by both algorithms.
        compareResults(greedyResult, bruteForceResult);
    }

    /**
     * Displays all jobs available for scheduling.
     */
    private static void displayAvailableJobs(List<Job> jobs) {

        System.out.println("\n==============================================");
        System.out.println("       RESOURCE ALLOCATION SCHEDULER");
        System.out.println("==============================================");

        System.out.println("\nAVAILABLE JOBS");

        System.out.printf(
                "%-8s %-12s %-12s %-15s %-15s%n",
                "Job ID",
                "Profit",
                "Duration",
                "Earliest Start",
                "Latest Start"
        );

        System.out.println(
                "--------------------------------------------------------------"
        );

        for (Job job : jobs) {

            System.out.printf(
                    "%-8s %-12d %-12d %-15d %-15d%n",
                    job.getId(),
                    job.getProfit(),
                    job.getDuration(),
                    job.getEarliestStart(),
                    job.getLatestStart()
            );
        }
    }

    /**
     * Displays the schedule generated by a scheduling algorithm.
     */
    private static void displayResult(
            String title,
            GreedyScheduler.Result result
    ) {

        System.out.println("\n==============================================");
        System.out.println("       " + title);
        System.out.println("==============================================");

        if (result.scheduledJobs.isEmpty()) {

            System.out.println("No jobs were scheduled.");

        } else {

            System.out.printf(
                    "%-10s %-12s %-12s %-12s%n",
                    "Job ID",
                    "Start",
                    "Finish",
                    "Profit"
            );

            System.out.println(
                    "----------------------------------------------"
            );

            for (
                    GreedyScheduler.ScheduledJob scheduledJob
                    : result.scheduledJobs
            ) {

                System.out.printf(
                        "%-10s %-12d %-12d %-12d%n",
                        scheduledJob.job.getId(),
                        scheduledJob.start,
                        scheduledJob.finish,
                        scheduledJob.job.getProfit()
                );
            }
        }

        // Display the total profit generated by the algorithm.
        System.out.println("----------------------------------------------");

        System.out.println(
                "Total Profit: " + result.totalProfit
        );
    }

    /**
     * Compares the total profits generated by the two algorithms.
     */
    private static void compareResults(
            GreedyScheduler.Result greedyResult,
            GreedyScheduler.Result bruteForceResult
    ) {

        System.out.println("\n==============================================");
        System.out.println("          ALGORITHM COMPARISON");
        System.out.println("==============================================");

        System.out.printf(
                "%-25s %10s%n",
                "Algorithm",
                "Total Profit"
        );

        System.out.println(
                "----------------------------------------------"
        );

        System.out.printf(
                "%-25s %10d%n",
                "Greedy Scheduler",
                greedyResult.totalProfit
        );

        System.out.printf(
                "%-25s %10d%n",
                "Brute Force Scheduler",
                bruteForceResult.totalProfit
        );

        System.out.println(
                "----------------------------------------------"
        );

        // Calculate the difference in profit between both algorithms.
        long profitDifference =
                bruteForceResult.totalProfit - greedyResult.totalProfit;

        System.out.println(
                "Profit Difference: " + profitDifference
        );

        // Determine whether the greedy algorithm achieved an optimal result.
        if (profitDifference == 0) {

            System.out.println(
                    "Result: The greedy algorithm found an optimal solution."
            );

        } else {

            System.out.println(
                    "Result: The greedy algorithm did not find an optimal solution."
            );
        }

        System.out.println("==============================================");
    }
}
